#!/usr/bin/env python3
############################################################################
# app/digit/tools/gen_samples.py
#
# Write every 20th MNIST test image, 500 in all, into
# app/digit/digit_samples.c.  bench runs both inference implementations
# on them to compare speed and accuracy.  Only numpy is needed.
#
#   gen_samples.py <mnist dir>
############################################################################

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from train import load_set  # noqa: E402

SAMPLES = 500

HEADER = """\
/****************************************************************************
 * app/digit/digit_samples.c
 *
 * %d MNIST test images, every %dth of the test set.
 * Generated by tools/gen_samples.py.
 ****************************************************************************/

#include <stdint.h>

#include "digit.h"

"""


def main():
    x, y = load_set(sys.argv[1], "t10k")
    step = len(x) // SAMPLES
    x = (x[::step][:SAMPLES] * 255).round().astype(int)
    y = y[::step][:SAMPLES]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                       "digit_samples.c")

    with open(out, "w") as f:
        f.write(HEADER % (SAMPLES, step))
        f.write("const uint8_t g_digit_sample_images[DIGIT_SAMPLES]"
                "[DIGIT_INPUTS] =\n{\n")
        for img in x.reshape(SAMPLES, -1):
            f.write("  {\n")
            for i in range(0, len(img), 28):
                f.write("    " + ",".join(str(v) for v in img[i:i + 28]) +
                        ",\n")
            f.write("  },\n")
        f.write("};\n\nconst uint8_t g_digit_sample_labels[DIGIT_SAMPLES] "
                "=\n{\n")
        for i in range(0, SAMPLES, 25):
            f.write("  " + ", ".join(str(v) for v in y[i:i + 25]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
