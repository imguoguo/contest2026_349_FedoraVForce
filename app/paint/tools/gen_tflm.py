#!/usr/bin/env python3
############################################################################
# app/paint/tools/gen_tflm.py
#
# Write the .tflite made by train_tflm.py into app/paint/digit_tflm_model.c
# as a C array for TFLite Micro.  No TensorFlow needed.
#
#   gen_tflm.py mnist_mlp.tflite
############################################################################

import hashlib
import os
import sys

HEADER = """\
/****************************************************************************
 * app/paint/digit_tflm_model.c
 *
 * 784-128-10 MLP for MNIST digits as a fully int8 TFLite model.
 * Generated by tools/gen_tflm.py from a %d byte .tflite,
 * md5 %s.
 ****************************************************************************/

#include <stdint.h>

#include "digit.h"

/* TFLite Micro wants the flatbuffer 16 byte aligned */

const uint8_t g_digit_tflm_model[%d] __attribute__((aligned(16))) =
{
"""


def main():
    data = open(sys.argv[1], "rb").read()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                       "digit_tflm_model.c")

    with open(out, "w") as f:
        f.write(HEADER % (len(data), hashlib.md5(data).hexdigest(),
                          len(data)))
        for i in range(0, len(data), 16):
            f.write("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) +
                    ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
