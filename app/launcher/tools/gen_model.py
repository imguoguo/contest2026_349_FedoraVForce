# Convert model.json (from train_digits.py) into launcher_model.c.
# Usage: python3 gen_model.py model.json ../launcher_model.c
import base64, json, sys

m = json.load(open(sys.argv[1]))
w1 = base64.b64decode(m['w1'])
w2 = base64.b64decode(m['w2'])


def arr(b, per=16):
    v = [str(x - 256 if x > 127 else x) for x in b]
    return ',\n'.join('  ' + ', '.join(v[i:i + per]) for i in range(0, len(v), per))


def farr(a, per=6):
    v = ['%.5ff' % x for x in a]
    return ',\n'.join('  ' + ', '.join(v[i:i + per]) for i in range(0, len(v), per))


banner = '/' + '*' * 76 + '\n'
end = ' ' + '*' * 76 + '/\n'
out = (banner + ' * app/launcher/launcher_model.c\n *\n'
       f" * Handwritten digit classifier weights: 784 -> {m['h']} (ReLU) -> 10 MLP\n"
       ' * trained on MNIST, int8 symmetric per-tensor weights, float biases.\n'
       f" * MNIST test accuracy: {m['acc_float'] * 100:.2f}% float, {m['acc_int8'] * 100:.2f}% int8.\n"
       ' * Generated by tools/gen_model.py, do not edit by hand.\n' + end + '\n'
       + banner + ' * Included Files\n' + end + '\n#include <stdint.h>\n\n#include "launcher.h"\n\n'
       + banner + ' * Public Data\n' + end + '\n'
       f"const float g_digit_w1_scale = {m['s1']:.9e}f;\n"
       f"const float g_digit_w2_scale = {m['s2']:.9e}f;\n\n"
       f"const int8_t g_digit_w1[784 * LAUNCHER_DIGIT_HIDDEN] =\n{{\n{arr(w1)}\n}};\n\n"
       f"const float g_digit_b1[LAUNCHER_DIGIT_HIDDEN] =\n{{\n{farr(m['b1'])}\n}};\n\n"
       f"const int8_t g_digit_w2[LAUNCHER_DIGIT_HIDDEN * 10] =\n{{\n{arr(w2)}\n}};\n\n"
       f"const float g_digit_b2[10] =\n{{\n{farr(m['b2'])}\n}};\n\n"
       + banner + ' * Public Functions\n' + end)
open(sys.argv[2], 'w').write(out)
